export function citation(doc, locale, section) {
  if (locale.startsWith('zh')) {
    const i = locale === 'zh-Hant' ? 0 : 1;
    const name = zhShort[doc.id]?.[i] ?? (doc.kind === 'priests-letter'
      ? `${doc.year}年${i ? '圣周四致司铎书' : '聖週四致司鐸書'}` : displayTitle(doc, locale));
    return `《${name}》${section ?? ''}`;
  }
  let name;
  if (doc.id === 'pastores-dabo-vobis') name = 'PDV';
  else if (doc.id === 'ecclesia-de-eucharistia') name = 'EdE';
  else if (doc.id === 'dominicae-cenae') name = 'Dominicae Cenae';
  else if (doc.id === 'a-concilio-constantinopolitano-i') name = 'A Concilio Constantinopolitano I';
  else if (doc.kind === 'priests-prayer') name = `${prayerShort[locale] ?? prayerShort.en} ${doc.year}`;
  else name = `${letterShort[locale] ?? letterShort.en} ${doc.year}`;
  const sep = /^[A-Z]{2,4}$/.test(name) ? ' ' : ', ';
  return section ? `${name}${sep}${section}` : name;
}

export function quoteWithCitation(text, doc, locale, section) {
  const cite = citation(doc, locale, section);
  if (locale.startsWith('zh')) return `「${text}」（${cite}）`;
  const [open, close] = quotes[locale] ?? quotes.en;
  return `${open}${text}${close} (${cite})`;
}

