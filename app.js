function repeatedTitle(doc, locale, part, index) {
  if (index > 3) return false;
  const value = fold(part.text, locale).replaceAll('·', '').replace(/^[«「『“"]|[»」』”"]$/gu, '');
  if (splitTitles[doc.id + '/' + locale]?.includes(index)) return true;
  if (value === fold(displayTitle(doc, locale), locale)) return true;
  if (/^(?:giovanni paolo|juan pablo|jean[- ]paul|john paul|johannes paul|jan pawel|ioanna? paulus) ii\.?$|^(?:іван пав(?:ло|іл) (?:іі|ii)|иоанн павел ii|يوحنا بولس الثاني|若望保[祿禄]二世)$/u.test(value)) return true;
  if (doc.kind === 'priests-letter' || doc.kind === 'priests-prayer') {
    return value.length < 250 && letterMastheads[locale]?.test(value);
  }
  if (doc.kind === 'post-synodal-apostolic-exhortation') {
    return index === 0 && /pastores dabo vobis|我要给你们牧者|我要給你們牧者|我將賜予你們牧人|ساعطيكم رعاة/u.test(value);
  }
  if (doc.kind === 'bishops-letter') {
    return (value.includes(fold(doc.title, locale)) && value.length < 400)
      || /^(?:lettera apostolica|apostolic letter|lettre apostolique|carta apostolica|apostolisches schreiben|apostolische brief|list apostolski|апостольское послание|апостольський лист|رسالة رسولية|宗座牧函|宗座书函)$/u.test(value);
  }
  return false;
}

function snippet(text, needle, locale) {
  if (text.length <= 240) return text;
  const index = Math.max(0, fold(text, locale).indexOf(needle));
  const start = Math.max(0, index - 65);
  const end = Math.min(text.length, start + 235);
  return (start ? '…' : '') + text.slice(start, end) + (end < text.length ? '…' : '');
}

function localeIndex(locale) {
  if (indexedLocale === locale) return index;
  indexedLocale = locale;
  index = catalog.entries.flatMap(doc => {
    const text = texts[doc.id + '/' + locale];
    if (!text) return [];
    const title = displayTitle(doc, locale);
    return [{doc, text:title, search:fold(title, locale)}, ...text.passages.flatMap((part, p) =>
      repeatedTitle(doc, locale, part, p) ? [] : [{doc, p, text:part.text, search:fold(part.text, locale)}])];
  });
  return index;
}

function row(doc, locale, detail, passage) {
  const article = element('article', '', 'entry' + (doc.kind === 'post-synodal-apostolic-exhortation' ? ' featured' : ''));
  const heading = element('h3', '');
  heading.append(link(displayTitle(doc, locale), route(doc.id, locale, passage)));
  setTitleLanguage(heading, locale);
  const body = element('div', '');
  body.append(heading);
  if (detail) body.append(detail);
  article.append(element('span', doc.year, 'year'), body);
  return article;
}

function readingNotes(text, locale) {
  const groups = text.noteGroups ?? [];
  const lookup = groups.map(group => new Map(group.notes.map(note => [note.number, note.text])));
  const dialog = element('dialog', '', 'note-dialog');
  const dialogTitle = element('h2', '');
  dialogTitle.id = 'note-title';
  dialog.setAttribute('aria-labelledby', dialogTitle.id);
  const noteText = element('p', '');
  const close = element('button', '×');
  close.setAttribute('aria-label', 'Close');
  close.onclick = () => dialog.close();
  dialog.append(close, dialogTitle, noteText);
  setTitleLanguage(dialog, locale);
  const panel = element('details', '', 'footnotes');
  panel.append(element('summary', noteLabels[locale]));
  setTitleLanguage(panel, locale);
  for (const group of groups) {
    if (group.title) panel.append(element('h3', group.title));
    const list = element('ol', '');
    for (const note of group.notes) {
      const item = element('li', note.text);
      if (note.number === '*') {
        item.className = 'star-note';
        item.prepend('* ');
      } else {
        item.value = Number(note.number);
      }
      list.append(item);
    }
    panel.append(list);
  }
  return {
    appendTo(parent) {
      if (groups.length) parent.append(panel, dialog);
    },
    render(block, part) {
      const notes = lookup[part.noteGroup === undefined ? 0 : part.noteGroup];
      if (!notes) return;
      const markers = /[\[［〔]\s*(\p{Nd}+)\s*[\]］〕]|[（(]\s*(\p{Nd}+)\s*[）)]|(?<=[\p{L}\p{P}])([*])/gu;
      let offset = 0;
      for (const marker of part.text.matchAll(markers)) {
        const number = (marker[1] ?? marker[2] ?? marker[3]).normalize('NFKC')
          .replace(/[٠-٩]/g, digit => String(digit.charCodeAt(0) - 0x660))
          .replace(/[۰-۹]/g, digit => String(digit.charCodeAt(0) - 0x6f0));
        if (!notes.has(number)) continue;
        if (offset === 0) block.replaceChildren();
        block.append(part.text.slice(offset, marker.index));
        const reference = element('sup', '');
        const button = element('button', number);
        button.setAttribute('aria-label', noteLabels[locale] + ' ' + number);
        button.onclick = () => {
          dialogTitle.textContent = noteLabels[locale] + ' ' + number;
          noteText.textContent = notes.get(number);
          dialog.showModal();
        };
        reference.append(button);
        block.append(reference);
        offset = marker.index + marker[0].length;
      }
      if (offset) block.append(part.text.slice(offset));
    },
  };
}

function renderLibrary() {
  const locale = select.value;
  const readable = catalog.entries.filter(doc => hasText(doc.id, locale)).length;
  const needle = fold(query.value, locale);
  el('view-title').textContent = needle ? 'Search results' : 'Collection';
  if (needle && readable && !Object.keys(texts).some(key => key.endsWith('/' + locale))) {
    status.textContent = 'Loading ' + names[locale] + '…';
    ensureLocale(locale).then(() => {
      if (select.value === locale) renderLibrary();
    }, () => {
      status.textContent = names[locale] + ' is not available offline yet. Connect once to download it.';
    });
    return;
  }
  if (needle) {
    const available = readable;
    const matches = localeIndex(locale).filter(item => item.search.includes(needle));
    status.textContent = available ? matches.length + ' matches across ' + available + ' searchable editions' : 'No indexed editions in ' + names[locale];
    const cards = matches.slice(0, 150).map(({doc, p, text}) => {
      const preview = element('p', snippet(text, needle, locale));
      preview.lang = locale;
      preview.dir = 'auto';
      return row(doc, locale, preview, p);
    });
    if (!cards.length) cards.push(element('p', available ? 'No passages match this search.' : 'Choose a reading language with indexed editions.', 'notice'));
    if (matches.length > 150) cards.push(element('p', 'Showing the first 150 matches. Refine the search to narrow the results.', 'notice'));
    results.replaceChildren(...cards);
    return;
  }
  status.textContent = readable + ' of ' + catalog.entries.length + ' editions readable in ' + names[locale];
  const ordered = [...catalog.entries].sort((a,b) =>
    Number(b.kind === 'post-synodal-apostolic-exhortation') - Number(a.kind === 'post-synodal-apostolic-exhortation') || a.year - b.year);
  results.replaceChildren(...ordered.map(doc => {
    if (hasText(doc.id, locale)) return row(doc, locale);
    const edition = doc.editions.find(item => item.locale === locale);
    const info = edition ? 'Edition unavailable in the reader' : 'No catalog edition in ' + names[locale];
    return row(doc, locale, element('p', info, 'meta'));
  }));
}

function renderRoute() {
  const params = new URLSearchParams(location.hash.slice(1));
  const requestedDoc = params.get('doc');
  const doc = catalog?.entries.find(item => item.id === requestedDoc);
  const locale = Object.hasOwn(names, params.get('lang')) ? params.get('lang') : select.value;
  const landing = !requestedDoc && location.hash !== '#library';
  const library = el('library');
  const enteringLibrary = library.hidden && !landing && !doc;
  el('landing').hidden = !landing;
  reader.hidden = !doc;
  library.hidden = landing || Boolean(doc);

  if (landing) {
    previousDocument = null;
    window.scrollTo(0, 0);
    return;
  }

  if (!doc) {
    if (catalog) renderLibrary();
    if (enteringLibrary) el('library-title').focus({preventScroll:true});
    if (previousDocument) window.scrollTo(0, position.get(previousDocument) ?? 0);
    previousDocument = null;
    return;
  }
  if (hasText(doc.id, locale) && !texts[doc.id + '/' + locale]) {
    reader.replaceChildren(element('p', 'Loading ' + names[locale] + '…', 'notice'));
    ensureLocale(locale).then(renderRoute, () => {
      reader.replaceChildren(link('Back to collection', '#library'),
        element('p', names[locale] + ' is not available offline yet. Connect once to download it.', 'notice'));
    });
    return;
  }
  if (!previousDocument) position.set(doc.id, window.scrollY);
  previousDocument = doc.id;
  select.value = locale;
  const back = link('Back to collection', '#library');
  const head = element('div', '', 'reader-head');
  const title = element('h1', displayTitle(doc, locale));
  setTitleLanguage(title, locale);
  head.append(element('p', doc.year + ' · Saint John Paul II', 'eyebrow'), title);
  const sources = element('div', '', 'sources');
  const edition = doc.editions.find(item => item.locale === locale);
  if (edition?.format === 'pdf') sources.append(link('Open source PDF', edition.url));
  head.append(element('p', names[locale], 'meta'), sources);
  reader.replaceChildren(back, head);

  const other = catalog.targetContentLocales.filter(language => language !== locale &&
    (hasText(doc.id, language) || doc.editions.some(item => item.locale === language)));
  if (other.length) {
    const options = element('div', '', 'sources');
    options.setAttribute('aria-label', 'Other editions');
    const currentSection = params.get('s') ?? undefined;
    for (const language of other) options.append(link(names[language], route(doc.id, language, undefined, currentSection)));
    head.append(options);
  }
  const text = texts[doc.id + '/' + locale];
  if (text) {
    if (text.translation?.type === 'ai-generated') {
      const [disclaimer, label] = translationNotices[locale];
      const notice = element('p', disclaimer + ' ', 'notice');
      setTitleLanguage(notice, locale);
      notice.append(link(label, text.source));
      reader.append(notice);
    } else if (text.translation?.type === 'published' || text.translation?.type === 'script-conversion') {
      const hans = locale === 'zh-Hans';
      const lines = [(hans ? '译本：' : '譯本：') + text.translation.credit];
      if (text.translation.type === 'script-conversion') {
        lines.push(hans ? '此简体文本由繁体原文转换字形而成，译文内容未经改动。' : '此繁體文本由簡體原文轉換字形而成，譯文內容未經改動。');
      }
      const notice = element('p', lines.join(' ') + ' ', 'notice');
      setTitleLanguage(notice, locale);
      notice.append(link(hans ? '阅读来源文本' : '閱讀來源文本', text.source));
      reader.append(notice);
    }
    const notes = readingNotes(text, locale);
    if (text.passages[0]?.text.endsWith('*') && repeatedTitle(doc, locale, text.passages[0], 0)) {
      notes.render(title, {text: title.textContent + '*'});
    }
    const body = element('article', '', 'reader-body');
    body.lang = locale;
    body.dir = 'auto';
    const sections = [];
    text.passages.forEach((part, i) => {
      if (repeatedTitle(doc, locale, part, i)) return;
      const block = element(part.heading ? 'h2' : 'p', part.text);
      block.id = 'passage-' + i;
      if (part.n !== undefined) {
        block.dataset.section = part.n;
        sections.push([part.n, i]);
      }
      notes.render(block, part);
      body.append(block);
    });
    if (sections.length) {
      const jump = element('select', '');
      jump.setAttribute('aria-label', sectionLabels[locale] ?? 'Section');
      jump.append(new Option((sectionLabels[locale] ?? 'Section') + ' …', ''));
      for (const [n] of sections) jump.append(new Option('§ ' + n, n));
      jump.onchange = () => {
        if (jump.value) location.hash = route(doc.id, locale, undefined, jump.value);
      };
      const bar = element('div', '', 'section-jump');
      bar.append(jump);
      head.append(bar);
    }
    reader.append(body);
    notes.appendTo(reader);
    const sectionStart = sections.find(([n]) => String(n) === params.get('s'));
    const target = document.getElementById('passage-' + (sectionStart ? sectionStart[1] : params.get('p')));
    if (target) {
      target.classList.add('match');
      target.tabIndex = -1;
      target.focus({preventScroll:true});
      target.scrollIntoView({block:'start'});
      return;
    }
  } else {
    reader.append(element('p', edition ? 'This edition is currently unavailable in the reader.' : 'The source catalog has no verified edition in this language.', 'notice'));
  }
  title.tabIndex = -1;
  title.focus({preventScroll:true});
  window.scrollTo(0, 0);
}

async function load(path) {
  const response = await fetch(path);
  if (!response.ok) throw new Error('Could not load ' + path);
  return response.json();
}

